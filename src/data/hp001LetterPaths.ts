// Helper to get HP001 model safely for any letter
export function getHP001LetterModel(letterChar: string): HP001LetterModel {
  const key = letterChar.toLowerCase().trim();
  if (HP001_LETTER_DATABASE[key]) {
    return HP001_LETTER_DATABASE[key];
  }
  // Fallback default
  return HP001_LETTER_DATABASE["a"];
}

